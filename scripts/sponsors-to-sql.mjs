// Manual import: reads data/sponsors/*.json and data/government-fees.json, checks them, and writes
// supabase/seeds/sponsors.generated.sql. You paste that file into the Supabase SQL Editor (runs as admin).
// No API keys are needed. Re-running is safe: sponsors are upserted by slug and their child rows are rebuilt.
import fs from "node:fs";
import path from "node:path";
import { scheduleRows } from "./build-model.mjs";

const root = path.resolve(import.meta.dirname, "..");
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a === null || a === undefined ? "null" : `array[${a.map(q).join(",")}]::text[]`);
const bool = (b) => (b ? "true" : "false");
const num = (n) => (n === null || n === undefined ? "null" : String(Math.round(n)));
const date = (d) => (d ? `${q(d)}::date` : "null");
const fail = (m) => { console.error("Data error: " + m); process.exit(1); };

const files = fs.readdirSync(path.join(root, "data/sponsors")).filter((f) => f.endsWith(".json")).sort();
const out = ["-- GENERATED by scripts/sponsors-to-sql.mjs. Do not edit by hand.", "begin;"];

for (const f of files) {
  const s = JSON.parse(fs.readFileSync(path.join(root, "data/sponsors", f), "utf8"));
  const sid = `(select id from public.sponsors where slug = ${q(s.slug)})`;
  if (!/^[a-z0-9-]+$/.test(s.slug)) fail(`${f}: bad slug`);
  if (s.record_status === "verified" && !s.designation_verified_at) fail(`${f}: verified sponsor needs designation_verified_at`);
  out.push(`-- ${s.name}`);
  out.push(`insert into public.sponsors (slug,name,website_url,contact_phone,address,designation_source_url,designation_verified_at,record_status,is_published,notes)
values (${q(s.slug)},${q(s.name)},${q(s.website_url)},${q(s.contact_phone)},${q(s.address)},${q(s.designation_source_url)},${date(s.designation_verified_at)},${q(s.record_status)},${bool(s.is_published)},${q(s.notes)})
on conflict (slug) do update set name=excluded.name, website_url=excluded.website_url, contact_phone=excluded.contact_phone, address=excluded.address,
  designation_source_url=excluded.designation_source_url, designation_verified_at=excluded.designation_verified_at, record_status=excluded.record_status,
  is_published=excluded.is_published, notes=excluded.notes;`);
  for (const t of ["sponsor_requirements", "sponsor_policies", "sponsor_fee_schedules", "sponsor_programs", "sponsor_sources"])
    out.push(`delete from public.${t} where sponsor_id = ${sid};`);
  const src = (key) => {
    if (key === null || key === undefined) return "null";
    const x = s.sources[key]; if (!x) fail(`${f}: unknown source key ${key}`);
    return `(select id from public.sponsor_sources where sponsor_id = ${sid} and url = ${q(x.url)} and info_type = ${q(x.info_type)})`;
  };
  for (const [k, x] of Object.entries(s.sources)) {
    if (!x.verified_at) fail(`${f}: source ${k} needs verified_at`);
    out.push(`insert into public.sponsor_sources (sponsor_id,url,info_type,verified_at,review_status,reviewer,note) values (${sid},${q(x.url)},${q(x.info_type)},${date(x.verified_at)},${q(x.review_status)},${q(x.reviewer)},${q(x.note)});`);
  }
  for (const p of s.programs)
    out.push(`insert into public.sponsor_programs (sponsor_id,category,fields,max_duration_months,record_status,designation_evidence,designation_source_id,verified_at,notes) values (${sid},${q(p.category)},${arr(p.fields ?? [])},${num(p.max_duration_months)},${q(p.record_status)},${q(p.designation_evidence ?? "sponsor_statement")},${src(p.designation_source)},${date(p.verified_at)},${q(p.notes)});`);
  for (const p of s.policies)
    out.push(`insert into public.sponsor_policies (sponsor_id,policy_key,value,detail,source_id,review_status,verified_at) values (${sid},${q(p.policy_key)},${q(p.value)},${q(p.detail)},${src(p.source)},${q(p.review_status)},${date(p.verified_at)});`);
  for (const r of s.requirements)
    out.push(`insert into public.sponsor_requirements (sponsor_id,category,requirement_type,description,source_id,review_status,verified_at) values (${sid},${q(r.category)},${q(r.requirement_type)},${q(r.description)},${src(r.source)},'verified',${date(s.designation_verified_at)});`);

  for (const r of scheduleRows(s)) {
    if (!s.sources[r.source]) fail(`${f}: schedule ${r.label} has no source`);
    const schedId = `(select id from public.sponsor_fee_schedules where sponsor_id = ${sid} and category = ${q(r.category)} and label = ${q(r.label)})`;
    out.push(`insert into public.sponsor_fee_schedules (sponsor_id,category,label,applies_to_residence,applies_to_education,currency,is_itemized_complete,inclusions_confirmed,notes,status,verified_at,source_id)
values (${sid},${q(r.category)},${q(r.label)},${arr(r.applies_to_residence)},${arr(r.applies_to_education)},'USD',${bool(r.is_itemized_complete)},${bool(r.inclusions_confirmed)},${q(r.notes)},${q(r.status)},${date(r.verified_at)},${src(r.source)});`);
    for (const c of r.components) {
      if (c.amount_cents !== null && c.amount_cents < 0) fail(`${f}: negative amount in ${r.label}`);
      out.push(`insert into public.sponsor_fee_components (schedule_id,component_type,label,amount_cents,per,is_mandatory,duration_min_months,duration_max_months,choice_group,notes) values (${schedId},${q(c.component_type)},${q(c.label)},${num(c.amount_cents)},${q(c.per)},${bool(c.is_mandatory)},${num(c.duration_min_months)},${num(c.duration_max_months)},${q(c.choice_group)},${q(c.notes)});`);
    }
    for (const i of r.inclusions) out.push(`insert into public.sponsor_fee_inclusions (schedule_id,service_key,detail) values (${schedId},${q(i.service_key)},${q(i.detail)});`);
  }
}
const gov = JSON.parse(fs.readFileSync(path.join(root, "data/government-fees.json"), "utf8"));
for (const g of gov.fees)
  out.push(`insert into public.government_fees (key,label,amount_cents,applies_to_categories,included_in_comparison,source_url,verified_at,review_status,note) values (${q(g.key)},${q(g.label)},${num(g.amount_cents)},${arr(g.applies_to_categories)},${bool(g.included_in_comparison)},${q(g.source_url)},${date(g.verified_at)},${q(g.review_status)},${q(g.note)})
on conflict (key) do update set label=excluded.label, amount_cents=excluded.amount_cents, applies_to_categories=excluded.applies_to_categories, included_in_comparison=excluded.included_in_comparison, source_url=excluded.source_url, verified_at=excluded.verified_at, review_status=excluded.review_status, note=excluded.note;`);
out.push("commit;");
fs.writeFileSync(path.join(root, "supabase/seeds/sponsors.generated.sql"), out.join("\n") + "\n");
console.log(`Wrote supabase/seeds/sponsors.generated.sql (${out.length} statements)`);
